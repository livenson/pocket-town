const pkgDir = new URL('../node_modules/@iconify-json/fluent-emoji-flat/', import.meta.url);
interface IconSet {
  width?: number;
  height?: number;
  icons: Record<string, { body: string; width?: number; height?: number }>;
  aliases?: Record<string, { parent: string }>;
}
const set: IconSet = JSON.parse(
  await readFile(fileURLToPath(new URL('icons.json', pkgDir)), 'utf8'),
);
const pkg: { version: string } = JSON.parse(
  await readFile(fileURLToPath(new URL('package.json', pkgDir)), 'utf8'),
);
const { version } = pkg;

const lines = NAMES.map((name) => {
  const icon = set.icons[name] ?? set.icons[set.aliases?.[name]?.parent ?? ''];
  if (!icon) throw new Error(`no picture called ${name}`);
  const w = icon.width ?? set.width ?? 32;
  const h = icon.height ?? set.height ?? 32;
  return `  '${name}': ${JSON.stringify({ w, h, body: icon.body })},`;
});

await writeFile(
  fileURLToPath(new URL('../src/design/thingArt.ts', import.meta.url)),
  `// Generated by scripts/make-thing-art.ts from @iconify-json/fluent-emoji-flat ${version}. Do not edit.
// Microsoft Fluent Emoji (flat): MIT License, Copyright (c) Microsoft Corporation.
// https://github.com/microsoft/fluentui-emoji
export const thingArt: Record<string, { w: number; h: number; body: string }> = {
${lines.join('\n')}
};
`,
);
console.log(`wrote ${NAMES.length} pictures`);
